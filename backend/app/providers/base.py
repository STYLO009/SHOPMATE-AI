"""Shared product provider contract.

Every provider adapter (sample dataset, authorized merchant API, affiliate
feed, user-provided URL) returns the same normalised structure so the rest of
the system never depends on a specific merchant.
"""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any, Optional


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


@dataclass
class ProviderProduct:
    """Normalised product record produced by a provider adapter."""

    provider_product_id: str
    title: str
    price: float
    merchant: str
    currency: str = "INR"
    brand: Optional[str] = None
    category: Optional[str] = None
    description: Optional[str] = None
    product_url: Optional[str] = None
    image_url: Optional[str] = None
    specifications: dict[str, Any] = field(default_factory=dict)
    rating: Optional[float] = None
    review_count: Optional[int] = None
    availability: str = "unknown"
    # "sample" | "merchant_api" | "affiliate_feed" | "user_url" | "public_dataset"
    source_type: str = "sample"
    source_name: str = "unknown"
    is_sample_data: bool = True
    last_verified_at: datetime = field(default_factory=utcnow)
    # Reviews supplied by the provider (never generated by the platform)
    reviews: list[dict[str, Any]] = field(default_factory=list)

    @property
    def dedupe_key(self) -> str:
        from app.utils.validators import product_dedupe_key

        return product_dedupe_key(self.title, self.brand, self.merchant)


class ProviderError(Exception):
    """Raised when a provider fails; the registry degrades gracefully."""

    def __init__(self, provider: str, message: str, retriable: bool = True):
        super().__init__(f"{provider}: {message}")
        self.provider = provider
        self.message = message
        self.retriable = retriable


@dataclass
class ProviderResult:
    products: list[ProviderProduct]
    provider_name: str
    is_sample_data: bool = False
    error: Optional[str] = None
    took_ms: int = 0


class ProductProvider(ABC):
    """Abstract product data provider."""

    name: str = "base"
    source_type: str = "sample"

    @abstractmethod
    async def search(
        self,
        query: str,
        category: Optional[str] = None,
        budget_min: Optional[float] = None,
        budget_max: Optional[float] = None,
        limit: int = 20,
    ) -> list[ProviderProduct]:
        """Return matching products. Must not fabricate data."""

    async def get_product(self, provider_product_id: str) -> Optional[ProviderProduct]:
        """Fetch a single product when the provider supports it."""
        results = await self.search(query=provider_product_id, limit=5)
        for p in results:
            if p.provider_product_id == provider_product_id:
                return p
        return None

    async def check_price(self, provider_product_id: str) -> Optional[ProviderProduct]:
        """Re-check a price. Default: fetch the product again."""
        return await self.get_product(provider_product_id)

    async def health(self) -> bool:
        try:
            await self.search(query="test", limit=1)
            return True
        except Exception:
            return False
